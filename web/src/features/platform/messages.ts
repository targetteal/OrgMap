export type PlatformMessage = keyof typeof rows;
const locales: Locale[] = [
  "pt-BR",
  "en-US",
  "es-ES",
  "fr-FR",
  "de-DE",
  "it-IT",
  "ja-JP",
  "nl-NL",
];
export const platformMessages = Object.fromEntries(
  locales.map((locale, index) => [
    locale,
    Object.fromEntries(
      Object.entries(rows).map(([key, values]) => [key, values[index]]),
    ),
  ]),
) as Record<Locale, Record<PlatformMessage, string>>;
export const platformTranslator = (locale: string) =>
  createMessageTranslator<PlatformMessage>(locale, platformMessages);
export function resourceLabel(
  type: string,
  translate: ReturnType<typeof platformTranslator>,
) {
  return Object.hasOwn(rows, type)
    ? translate(type as PlatformMessage)
    : translate("otherResources");
}

export function notificationEventLabel(event:string, fallback:string, locale:string) {
 const t=platformTranslator(locale);
 if (event.endsWith('CommentAdded')) return t('CommentAdded');
 return Object.hasOwn(rows,event) ? t(event as PlatformMessage) : fallback;
}
