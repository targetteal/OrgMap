export function useGovernanceLocalization(){
 const regional=useLocalization();
 const translate=createMessageTranslator(regional.locale,stateMessages);
 return {...regional,m:governanceMiscTranslator(regional.locale),p:governanceProcessTranslator(regional.locale),f:governanceFormTranslator(regional.locale),d:governanceDetailTranslator(regional.locale),ui:governanceListTranslator(regional.locale),countLabel:(value:number,kind:GovernanceCountKind)=>formatGovernanceCount(value,kind,regional.locale),label:(value?:string)=>value ? (Object.hasOwn(stateMessages["pt-BR"],value) ? translate(value as GovernanceState) : value) : "—"};
}
